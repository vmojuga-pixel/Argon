export function renderOmniUI() {
  const parts = [];
  parts.push('<!DOCTYPE html>');
  parts.push('<html lang="ms" class="dark"><head>');
  parts.push('<meta charset="UTF-8">');
  parts.push('<meta name="viewport" content="width=device-width,initial-scale=1.0">');
  parts.push('<title>Argon Omni-Overlord Console</title>');
  parts.push('<script src="https://cdn.tailwindcss.com"><' + '/script>');
  parts.push('</head><body class="bg-slate-950 text-slate-200 min-h-screen font-sans">');
  parts.push('<header class="border-b border-slate-800 bg-slate-900/90 sticky top-0 z-50 backdrop-blur">');
  parts.push('<div class="max-w-7xl mx-auto px-4 md:px-6 h-14 flex items-center justify-between flex-wrap gap-2">');
  parts.push('<div class="flex items-center gap-3">');
  parts.push('<div class="w-2.5 h-2.5 rounded-full bg-emerald-500 animate-pulse"></div>');
  parts.push('<span class="font-mono font-bold text-sm text-white">ARGON <span class="text-emerald-400">OMNI-OVERLORD</span></span>');
  parts.push('<span class="text-[10px] font-mono bg-slate-800 text-cyan-400 px-2 py-0.5 rounded border border-slate-700">MULTI-REPO + E2E</span>');
  parts.push('</div>');
  parts.push('<div class="flex items-center gap-2">');
  parts.push('<input id="apiKey" placeholder="X-API-Key" class="bg-slate-950 border border-slate-700 rounded px-2 py-1.5 text-xs font-mono w-36 md:w-48" />');
  parts.push('<button onclick="askReport()" class="text-xs font-mono bg-cyan-600 hover:bg-cyan-500 text-white font-bold px-3 py-2 rounded">REPORT</button>');
  parts.push('</div></div></header>');
  parts.push('<main class="max-w-7xl mx-auto px-4 md:px-6 py-5 grid grid-cols-1 lg:grid-cols-12 gap-5">');
  parts.push('<div class="lg:col-span-5 space-y-4">');
  parts.push('<div class="bg-slate-900 border border-slate-800 rounded-xl p-5 space-y-3">');
  parts.push('<h2 class="text-xs font-mono uppercase tracking-wider text-emerald-400 font-bold">1. Target Repo + Arahan</h2>');
  parts.push('<div class="grid grid-cols-3 gap-2">');
  parts.push('<div class="col-span-2"><label class="block text-[10px] font-mono text-slate-400 mb-1">Repo (owner/repo)</label>');
  parts.push('<input id="repo" value="vmojuga-pixel/Argon" class="w-full bg-slate-950 border border-slate-700 rounded p-2 text-xs font-mono text-white" /></div>');
  parts.push('<div><label class="block text-[10px] font-mono text-slate-400 mb-1">Branch</label>');
  parts.push('<input id="branch" value="main" class="w-full bg-slate-950 border border-slate-700 rounded p-2 text-xs font-mono text-white" /></div>');
  parts.push('</div>');
  parts.push('<div class="flex gap-2">');
  parts.push('<input id="slug" placeholder="slug (cth: omni-demo)" class="flex-1 bg-slate-950 border border-slate-700 rounded p-2 text-xs font-mono text-white" />');
  parts.push('<button onclick="scanRepo()" class="bg-slate-800 hover:bg-slate-700 text-cyan-400 border border-slate-700 font-mono text-xs px-3 py-2 rounded">SCAN</button>');
  parts.push('</div>');
  parts.push('<div id="scanBox" class="bg-slate-950 border border-slate-800 rounded p-3 text-[11px] font-mono text-slate-400">// Scan repo or type directive</div>');
  parts.push('<textarea id="directive" rows="3" class="w-full bg-slate-950 border border-slate-700 rounded p-2.5 text-xs font-mono text-white" placeholder="Full stack website lengkap end-to-end..."></textarea>');
  parts.push('<button id="execBtn" onclick="execute()" class="w-full bg-emerald-600 hover:bg-emerald-500 text-white font-mono font-bold py-2.5 rounded text-xs">SCAN + BUILD + COMMIT + DEPLOY</button>');
  parts.push('</div>');
  parts.push('<div class="bg-slate-900 border border-slate-800 rounded-xl p-5">');
  parts.push('<h2 class="text-xs font-mono uppercase tracking-wider text-cyan-400 font-bold mb-2">2. Report</h2>');
  parts.push('<div id="reportText" class="bg-slate-950 border border-slate-800 rounded p-3 text-xs font-mono text-slate-300 mb-3">// Ready</div>');
  parts.push('<div class="grid grid-cols-3 gap-2 font-mono text-center text-xs">');
  parts.push('<div class="bg-slate-950 border border-slate-800 p-2 rounded"><div class="text-[10px] text-slate-400">REPOS</div><div id="mRepo" class="text-base font-bold text-cyan-400">0</div></div>');
  parts.push('<div class="bg-slate-950 border border-slate-800 p-2 rounded"><div class="text-[10px] text-slate-400">APPS</div><div id="mApps" class="text-base font-bold text-emerald-400">0</div></div>');
  parts.push('<div class="bg-slate-950 border border-slate-800 p-2 rounded"><div class="text-[10px] text-slate-400">HEALS</div><div id="mHeals" class="text-base font-bold text-amber-400">0</div></div>');
  parts.push('</div></div></div>');
  parts.push('<div class="lg:col-span-7"><div class="bg-slate-900 border border-slate-800 rounded-xl p-5 flex flex-col h-full min-h-[500px]">');
  parts.push('<div class="flex items-center justify-between border-b border-slate-800 pb-2 mb-3 flex-wrap gap-2">');
  parts.push('<div class="flex gap-2">');
  parts.push('<button onclick="tab(\'live\')" id="tLive" class="px-3 py-1.5 text-xs font-mono rounded bg-emerald-600 text-white font-bold">LIVE PREVIEW</button>');
  parts.push('<button onclick="tab(\'files\')" id="tFiles" class="px-3 py-1.5 text-xs font-mono rounded bg-slate-950 text-slate-400">FILES</button>');
  parts.push('</div>');
  parts.push('<span id="liveUrl" class="text-xs font-mono text-cyan-400">Standby</span>');
  parts.push('</div>');
  parts.push('<div id="vLive" class="flex-1 bg-slate-950 border border-slate-800 rounded overflow-hidden min-h-[450px] flex items-center justify-center text-slate-500 font-mono text-xs">');
  parts.push('// Submit directive to see live preview');
  parts.push('</div>');
  parts.push('<div id="vFiles" class="hidden flex-1 bg-slate-950 border border-slate-800 rounded p-4 font-mono text-xs overflow-y-auto max-h-[450px]">');
  parts.push('<div id="filesList" class="text-slate-400">// Files list akan muncul di sini</div>');
  parts.push('</div></div></div>');
  parts.push('</main>');

  parts.push('<script>');
  parts.push('const $ = (id) => document.getElementById(id);');
  parts.push('const API = location.origin;');
  parts.push('const hdr = () => ({ "Content-Type": "application/json", "X-API-Key": $("apiKey").value.trim() });');
  parts.push('function tab(t) {');
  parts.push('  ["Live","Files"].forEach(x => { $("v"+x).classList.add("hidden"); $("t"+x).className = "px-3 py-1.5 text-xs font-mono rounded bg-slate-950 text-slate-400"; });');
  parts.push('  $("v"+t).classList.remove("hidden");');
  parts.push('  $("t"+t).className = "px-3 py-1.5 text-xs font-mono rounded bg-emerald-600 text-white font-bold";');
  parts.push('}');
  parts.push('async function scanRepo() {');
  parts.push('  const repo = $("repo").value.trim();');
  parts.push('  const branch = $("branch").value.trim() || "main";');
  parts.push('  $("scanBox").innerHTML = "<span class=\\"text-amber-400\\">Scanning " + repo + "...</span>";');
  parts.push('  try {');
  parts.push('    const r = await fetch(API + "/omni/scan-repo", { method: "POST", headers: hdr(), body: JSON.stringify({ targetRepo: repo, branch }) });');
  parts.push('    const d = await r.json();');
  parts.push('    if (!r.ok) { $("scanBox").innerHTML = "<span class=\\"text-rose-400\\">Error: " + (d.error || r.status) + "</span>"; return; }');
  parts.push('    if (!d.scanned) { $("scanBox").innerHTML = "<span class=\\"text-amber-400\\">" + (d.note || "skip") + "</span>"; return; }');
  parts.push('    $("scanBox").innerHTML = "<div class=\\"text-emerald-400 font-bold\\">OK " + d.repo + " (" + d.branch + ")</div><div>files: " + d.fileCount + " | stack: " + (d.detectedStack || []).join(", ") + "</div>";');
  parts.push('  } catch (e) { $("scanBox").innerHTML = "<span class=\\"text-rose-400\\">Network: " + e.message + "</span>"; }');
  parts.push('}');
  parts.push('async function execute() {');
  parts.push('  const repo = $("repo").value.trim();');
  parts.push('  const branch = $("branch").value.trim() || "main";');
  parts.push('  const slug = $("slug").value.trim();');
  parts.push('  const directive = $("directive").value.trim();');
  parts.push('  if (!repo || !directive) return alert("Repo + directive required");');
  parts.push('  if (!$("apiKey").value.trim()) return alert("X-API-Key required");');
  parts.push('  const btn = $("execBtn");');
  parts.push('  btn.disabled = true; btn.innerText = "BUILDING...";');
  parts.push('  try {');
  parts.push('    const r = await fetch(API + "/omni/execute", { method: "POST", headers: hdr(), body: JSON.stringify({ targetRepo: repo, branch, slug, directive }) });');
  parts.push('    const d = await r.json();');
  parts.push('    if (!r.ok) alert("Error: " + (d.error || r.status));');
  parts.push('    else { renderResult(d); await askReport(); }');
  parts.push('  } catch (e) { alert("Network: " + e.message); }');
  parts.push('  btn.disabled = false; btn.innerText = "SCAN + BUILD + COMMIT + DEPLOY";');
  parts.push('}');
  parts.push('function renderResult(record) {');
  parts.push('  const url = (record.deployment && record.deployment.liveUrl) || "-";');
  parts.push('  $("liveUrl").innerText = "LIVE: " + url;');
  parts.push('  const vLive = $("vLive");');
  parts.push('  vLive.innerHTML = "<div class=\\"p-5 w-full\\">" +');
  parts.push('    "<div class=\\"bg-emerald-500/20 border border-emerald-500/40 rounded p-3 mb-4\\">" +');
  parts.push('    "<div class=\\"font-bold text-emerald-300 text-sm\\">LIVE: " + record.appSlug + "</div>" +');
  parts.push('    "<div class=\\"text-slate-400 text-xs mt-1\\">" + record.targetRepo + " | " + record.branch + "</div>" +');
  parts.push('    "<div class=\\"text-cyan-400 text-xs mt-2\\">" + url + "</div></div>" +');
  parts.push('    "<div class=\\"bg-slate-900 border border-slate-800 rounded p-3\\">" +');
  parts.push('    "<div class=\\"text-cyan-400 text-xs mb-2\\">// API ENDPOINTS</div>" +');
  parts.push('    "<div class=\\"text-slate-400 text-xs leading-relaxed\\">GET /health<br>GET /api/items<br>POST /api/items<br>DELETE /api/items/:id</div></div>" +');
  parts.push('    "<div class=\\"text-slate-500 text-xs mt-3\\">Deploy: " + ((record.deployment && record.deployment.mode) || "n/a") + " | Commit: " + ((record.gitCommit && record.gitCommit.commitSha) || "n/a").slice(0, 12) + "</div></div>";');
  parts.push('  $("filesList").innerHTML = "<div class=\\"p-3 bg-slate-900 border border-slate-800 rounded\\"><div class=\\"text-emerald-400 font-bold mb-2\\">ATOMIC COMMIT: " + record.targetRepo + " (" + record.branch + ")</div>" + (record.generatedFiles || []).map(f => "<div class=\\"text-slate-300\\">- <span class=\\"text-amber-300\\">" + f + "</span></div>").join("") + "</div>";');
  parts.push('}');
  parts.push('async function askReport() {');
  parts.push('  try {');
  parts.push('    const r = await fetch(API + "/omni/report", { headers: hdr() });');
  parts.push('    const d = await r.json();');
  parts.push('    if (!r.ok) { $("reportText").innerText = "Error: " + (d.error || r.status); return; }');
  parts.push('    $("reportText").innerText = d.executiveSummary || "ok";');
  parts.push('    $("mRepo").innerText = (d.metrics && d.metrics.totalRepos) || 0;');
  parts.push('    $("mApps").innerText = (d.metrics && d.metrics.totalProjects) || 0;');
  parts.push('    $("mHeals").innerText = (d.metrics && d.metrics.totalAutoHeals) || 0;');
  parts.push('  } catch (e) { $("reportText").innerText = "Network: " + e.message; }');
  parts.push('}');
  parts.push('document.addEventListener("DOMContentLoaded", () => {');
  parts.push('  const s = localStorage.getItem("argon_key");');
  parts.push('  if (s) $("apiKey").value = s;');
  parts.push('  $("apiKey").addEventListener("change", () => localStorage.setItem("argon_key", $("apiKey").value.trim()));');
  parts.push('});');
  parts.push('<' + '/script>');
  parts.push('</body></html>');

  return parts.join('\n');
}
